"""Run Phase 2 (EDA): tables to results/eda, figures to results/figures, numbers to docs/eda_numbers.md.

Usage: python -m mandi.run_eda
Everything that can drive a modelling choice is computed on dates <= eda.train_end (2019-12-31). Tables whose
name ends in `_full` cover 2014-2024 and are for description only.
"""
from __future__ import annotations

import logging

import numpy as np
import pandas as pd

from mandi import eda, eda_plots
from mandi.config import ROOT, load_config
from mandi.run_phase1 import df_to_md

logger = logging.getLogger(__name__)


def main() -> None:
    """Compute all EDA tables and figures."""
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    cfg = load_config()
    ec = cfg["eda"]
    tables = ROOT / ec["tables_dir"]
    figs = ROOT / ec["figures_dir"]
    tables.mkdir(parents=True, exist_ok=True)
    events = ec["events"]
    min_days = ec["min_days_per_week"]

    panel = eda.load_panel(ROOT / cfg["paths"]["panel"])
    train = panel[panel["date"] <= ec["train_end"]]
    # guard for the evidence rule: everything below that drives modelling uses `train`, never `panel`
    assert train["date"].max() <= pd.Timestamp(ec["train_end"]) and train["date"].max() < pd.Timestamp(cfg["backtest"]["first_test_date"])
    logger.info("panel %d rows; train (<= %s) %d rows", len(panel), ec["train_end"], len(train))

    doc: list[str] = ["# EDA numbers (generated by `python -m mandi.run_eda`)", "",
                      f"Tables marked **TRAIN** use dates up to {ec['train_end']} and may drive modelling choices. "
                      "Tables marked **FULL** cover 2014-2024 and are descriptive only.", ""]

    def add(title: str, df: pd.DataFrame, name: str, note: str = "", index: bool = False) -> None:
        df = df.reset_index() if index else df
        df.to_csv(tables / f"{name}.csv", index=False)
        doc.extend([f"## {title}", "", note, "", df_to_md(df), ""])

    # ---- weekly series (train)
    wp_raw = eda.weekly_log_series(train, "modal_price", min_days)
    wp = eda.fill_weekly_gaps(wp_raw, ec["weekly_fill_weeks"])
    wa = eda.weekly_log_series(train, "arrivals_tonnes", min_days)
    cov = pd.DataFrame({
        "weeks_in_span": [wp_raw[m].loc[wp_raw[m].first_valid_index():].shape[0] for m in wp.columns],
        "valid_weeks": wp_raw.notna().sum().values,
        "valid_after_1wk_fill": wp.notna().sum().values,
        "longest_segment_weeks": [len(eda.longest_segment(wp[m])) for m in wp.columns],
    }, index=wp.columns)
    add("Weekly series coverage (TRAIN)", cov.reset_index(names="market"), "weekly_coverage_train",
        f"Weekly mean of observed days; a week needs >= {min_days} observed days; gaps of <= {ec['weekly_fill_weeks']} week filled by carrying forward (EDA only).")

    # ---- trend / yearly summary (full, description)
    add("Yearly price summary (FULL, description)", eda.yearly_summary(panel, min_days), "yearly_summary_full")
    add("Events: median price 4 weeks before vs after (FULL, descriptive, no causal claim)",
        eda.event_windows(panel, events), "event_windows_full")

    # ---- seasonality (train)
    wd = eda.weekday_effect(train)
    add("Weekday effects (TRAIN)", wd, "weekday_effects_train", "Relative to the same Monday-Sunday week's mean of observed days; weeks with >= 4 observed days.")
    monthly = eda.monthly_log_series(train)
    add("Yearly seasonality via STL on monthly log prices (TRAIN)", eda.yearly_seasonality(monthly), "yearly_seasonality_train",
        "STL period 12, robust. Seasonal strength F_S in [0, 1]; consistency = mean pairwise correlation of yearly month-profiles.")

    # ---- price vs arrivals (train)
    s_tab, lag_tab = eda.price_arrivals(train, min_days)
    add("Price vs arrivals, weekly (TRAIN)", s_tab, "price_arrivals_train")
    add("Lagged cross-correlation: weekly price change vs arrivals change k weeks earlier (TRAIN)", lag_tab.pivot(index="market", columns="arrivals_lag_weeks",
        values="corr_price_change_vs_lagged_arrivals_change").reset_index(), "price_arrivals_lagged_train")

    # ---- co-movement
    co_tr = eda.comovement(train, min_days)
    co_full = eda.comovement(panel, min_days)
    add("Correlation of weekly log price CHANGES (TRAIN)", co_tr["changes"], "comove_changes_train", index=True)
    add("Correlation of weekly log price LEVELS (TRAIN)", co_tr["levels"], "comove_levels_train", index=True)
    add("Correlation of weekly log price CHANGES (FULL, description)", co_full["changes"], "comove_changes_full", index=True)
    add("Lead-lag correlation of weekly changes, lag k = corr(a_t, b_{t+k}) (TRAIN)", co_tr["lead_lag_changes"], "comove_leadlag_train")

    # ---- stationarity, ACF, PACF (train)
    add("ADF and KPSS on weekly log price (TRAIN)", eda.stationarity_table(wp), "stationarity_train",
        "ADF null: unit root. KPSS null: stationary (p-values are clipped to 0.01-0.10 by statsmodels).")
    nl = 26
    acf_lvl = {m: eda.pairwise_acf_pacf(wp[m], nl) for m in wp.columns}
    acf_dif = {m: eda.pairwise_acf_pacf(wp[m].diff(), nl) for m in wp.columns}
    key_lags = pd.DataFrame({m: acf_dif[m].set_index("lag").loc[[1, 2, 3, 4, 13, 26], "acf"] for m in acf_dif}).round(3)
    add("ACF of weekly log price differences at selected lags (TRAIN)", key_lags.reset_index(names="lag_weeks"), "acf_diff_key_lags_train")
    pk = pd.DataFrame({m: acf_dif[m].set_index("lag").loc[[1, 2, 3, 4], "pacf"] for m in acf_dif}).round(3)
    add("PACF of weekly log price differences at lags 1-4 (TRAIN)", pk.reset_index(names="lag_weeks"), "pacf_diff_train")
    dacf = eda.daily_pairwise_acf(train)
    add("Daily log-change ACF, observed pairs only, lags 1-7 (TRAIN)", dacf[dacf["lag_days"] <= 7].pivot(index="lag_days", columns="market", values="acf").round(3).reset_index(), "daily_acf_train")

    # ---- transformation, volatility, breaks
    add("Variance vs level (TRAIN)", eda.transform_check(train), "transform_check_train")
    add("CUSUM stability test of AR(1) on weekly log price (TRAIN)", eda.cusum_ar1(wp), "cusum_train",
        "Small p-value = AR(1) parameters not stable over 2014-2019.")
    wp_full = eda.fill_weekly_gaps(eda.weekly_log_series(panel, "modal_price", min_days), ec["weekly_fill_weeks"])
    add("CUSUM stability test of AR(1) on weekly log price (FULL, description)", eda.cusum_ar1(wp_full), "cusum_full")
    d = wp.diff()
    early, late = d[d.index <= "2017-12-31"], d[d.index > "2017-12-31"]
    add("Std of weekly log change: 2014-2017 vs 2018-2019 (TRAIN)",
        pd.DataFrame({"std_2014_2017": early.std().round(3), "std_2018_2019": late.std().round(3), "ratio": (late.std() / early.std()).round(2)}).reset_index(names="market"),
        "volatility_split_train")

    # ---- missingness
    mt, mf = eda.missingness(train), eda.missingness(panel)
    add("Closure weekday per market (TRAIN)", mt["closure"], "closure_weekday_train", "Weekday with > 90% of days missing.", index=True)
    add("Missing share by weekday (TRAIN)", mt["by_weekday"], "missing_by_weekday_train", index=True)
    add("Missingness totals (TRAIN)", mt["totals"], "missing_totals_train", index=True)
    add("Missingness totals (FULL)", mf["totals"], "missing_totals_full", index=True)
    add("Unexpected missing share by month (TRAIN)", mt["by_month"], "missing_by_month_train", "Closure weekday excluded.", index=True)
    add("Unexpected missing share by year (FULL)", mf["by_year"], "missing_by_year_full", "Closure weekday excluded.", index=True)
    add("Unexpected missing vs local price/arrivals level (TRAIN)", eda.missing_vs_level(mt["_panel"]), "missing_vs_level_train",
        "Unexpected-missing rate on open days, by tercile of the local median level (15 days before and after, day excluded).")
    add("Gaps of 14+ missing days (FULL)", eda.gap_table(mf["_panel"]), "gaps_14plus_full")
    cm_tr, cm_full = eda.cross_market_missing(mt["_panel"]), eda.cross_market_missing(mf["_panel"])
    add("Do markets miss the same days? Unexpected-missing overlap (TRAIN)", cm_tr["pairs"], "missing_pairs_train")
    mm = cm_full["many_markets_missing"]
    add("Days with >= 4 markets unexpectedly missing (FULL)", mm, "missing_many_markets_full",
        f"{len(mm)} days. Of these, {int(((pd.to_datetime(mm['date']).dt.month == 1) & (pd.to_datetime(mm['date']).dt.day == 26)).sum())} are 26 Jan, "
        f"{int(((pd.to_datetime(mm['date']).dt.month == 8) & (pd.to_datetime(mm['date']).dt.day == 15)).sum())} are 15 Aug, "
        f"{int(((pd.to_datetime(mm['date']).dt.month == 5) & (pd.to_datetime(mm['date']).dt.day == 1)).sum())} are 1 May, "
        f"{int((pd.to_datetime(mm['date']).between('2020-03-23', '2020-06-30')).sum())} fall between 23 Mar and 30 Jun 2020.")
    add("Share of open markets missing on fixed-date public holidays (FULL)", cm_full["holidays"], "missing_holidays_full")
    add("Unexpected missing rate on festival vs other open days (TRAIN)", cm_tr["festival"], "missing_festival_train", index=True)

    # ---- figures
    ev = events
    eda_plots.price_trend(panel, ev, figs)
    eda_plots.yearly_seasonality(panel, figs)
    eda_plots.weekday_effect(wd, figs)
    eda_plots.price_vs_arrivals(wp, wa, lag_tab, figs)
    eda_plots.comovement(co_tr, eda.weekly_log_series(panel, "modal_price", min_days), figs)
    eda_plots.acf_pacf(acf_lvl, "Weekly log price LEVELS, 2014-2019: ACF (top) and PACF (bottom), dashed = approx. 95% band", "06a_acf_pacf_levels.png", figs)
    eda_plots.acf_pacf(acf_dif, "Weekly log price DIFFERENCES, 2014-2019: ACF (top) and PACF (bottom), dashed = approx. 95% band", "06b_acf_pacf_differences.png", figs)
    eda_plots.daily_acf(dacf, figs)
    eda_plots.missingness(mt | {"by_year": mf["by_year"]}, figs)
    eda_plots.missing_timeline(mf["_panel"], ev, figs)
    eda_plots.volatility(panel, eda.weekly_log_series(panel, "modal_price", min_days), ev, figs)
    eda_plots.transform_check(train, figs)

    ev_tab = pd.DataFrame(events)[["id", "date", "kind", "precision", "label", "source"]]
    doc.extend(["## Events marked on the figures", "", df_to_md(ev_tab)])
    (ROOT / cfg["paths"]["docs"] / "eda_numbers.md").write_text("\n".join(doc), encoding="utf-8")
    logger.info("wrote %d figures to %s and numbers to docs/eda_numbers.md", len(list(figs.glob("*.png"))), figs)


if __name__ == "__main__":
    main()
