"""Run Phase 1 end to end: load, rank markets, clean, build the daily panel, write logs.

Usage: python -m mandi.run_phase1
"""
from __future__ import annotations

import logging
from pathlib import Path

import pandas as pd

from mandi import clean, ingest
from mandi.config import ROOT, load_config

logger = logging.getLogger(__name__)


def df_to_md(df: pd.DataFrame) -> str:
    """Render a DataFrame as a markdown table (no tabulate dependency)."""
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines) + "\n"


def main() -> None:
    """Run the Phase 1 pipeline using configs/config.yaml."""
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    cfg = load_config()
    seed_note = cfg["seed"]  # no randomness in Phase 1; seed recorded for completeness
    log = clean.CleaningLog()

    interim = ROOT / cfg["paths"]["interim"]
    processed = ROOT / cfg["paths"]["processed"]
    docs = ROOT / cfg["paths"]["docs"]
    for d in (interim, processed, docs):
        d.mkdir(parents=True, exist_ok=True)

    # 1. load and basic row rules on all Maharashtra rows
    df = ingest.load_state_rows(cfg)
    start, end = pd.Timestamp(cfg["data"]["start_date"]), pd.Timestamp(cfg["data"]["end_date"])
    out_of_range = int(((df["date"] < start) | (df["date"] > end)).sum())
    log.add("load", f"rows outside {start.date()}..{end.date()}", out_of_range, "dropped" if out_of_range else "none",
            f"{len(df):,} {cfg['data']['state']} rows loaded; onion only (file is onion-only, group=Vegetables)")
    df = df[(df["date"] >= start) & (df["date"] <= end)]
    df = clean.normalise_names(df, log)
    df = clean.drop_exact_duplicates(df, log)

    # 2. coverage and ranking of all markets (before choosing)
    total_days = (end - start).days + 1
    cov = clean.market_coverage(df, total_days, end)
    rk = cfg["ranking"]
    ranked = clean.rank_markets(cov, rk["min_observed_days"], rk["max_gap_days"], rk["always_show"])

    # 3. chosen markets only
    chosen = cfg["markets"]
    missing = [m for m in chosen if m not in set(df["market_key"])]
    if missing:
        raise ValueError(f"Markets in config not found in data: {missing}")
    sub = df[df["market_key"].isin(chosen)].copy()
    primary = clean.choose_primary_variety(sub)
    sub = clean.select_primary_rows(sub, primary, log)
    sub = clean.drop_invalid_prices(sub, log)
    sub = clean.flag_stale_runs(sub, cfg["cleaning"]["stale_run_min_length"], log)

    # 4. calendar columns and daily panel
    cal, n_conflict = ingest.load_calendar(cfg)
    log.add("calendar", "dates whose festival/crop-season flags differ between rows", n_conflict,
            "first row kept" if n_conflict else "none", "calendar columns taken from the file, one row per date")
    panel = clean.build_daily_grid(sub, cal)

    # 5. outlier flags (on the uncorrected series), review table, approved corrections, then feature fills
    log.add("outliers", "rule history: first version (MAD floor only) gave 223 flags, mostly Rs 50-100 tick moves where MAD = 0; "
            "a minimum distance from the median was added after seeing that. Threshold 0.3 accepted by reviewer, not tuned further",
            223, "rule changed", "min_abs_log_dev = 0.3, chosen after seeing the 223 flags")
    panel = clean.flag_outliers(panel, cfg["cleaning"]["outlier"], log)
    review = clean.build_review_table(panel, cfg["cleaning"]["outlier"])
    panel = clean.apply_corrections(panel, cfg.get("corrections", []), log)
    panel = clean.add_ffill_columns(panel, cfg["cleaning"]["max_ffill_gap_days"], log)

    # 6. save
    panel = panel.sort_values(["market_key", "date"]).reset_index(drop=True)
    panel.to_parquet(ROOT / cfg["paths"]["panel"], index=False)
    review.to_csv(interim / "outlier_review.csv", index=False)
    cov.to_csv(interim / "market_coverage_all.csv", index=False)

    intro = (f"Generated by `python -m mandi.run_phase1` (seed {seed_note}). Every rule, how many rows it touched, "
             "and what was done. Values are dropped only when a price is missing or non-positive, and set to missing "
             "only for the reviewer-approved corrections (originals kept in the *_raw columns). Other outliers, "
             "stale runs and order violations are flagged, never changed.")
    (docs / "cleaning_log.md").write_text(log.to_markdown("Cleaning log", intro), encoding="utf-8")

    chosen_cov = cov[cov["market_key"].isin(chosen)]
    text = ["# Market coverage", "",
            f"Period {start.date()} to {end.date()} ({total_days} days). Primary-variety series only; arrivals once per market-day. "
            "Missing share is given against all 4,018 days and against each market's own span (first observed date to 2024-12-31).", "",
            "## Chosen markets", "", df_to_md(chosen_cov), "",
            f"## Maharashtra markets with >= {rk['min_observed_days']} observed days and longest gap <= {rk['max_gap_days']} days, "
            "ranked by median arrivals", "", df_to_md(ranked)]
    (docs / "market_coverage.md").write_text("\n".join(text), encoding="utf-8")

    logger.info("Panel: %d rows, %d markets -> %s", len(panel), panel["market_key"].nunique(), cfg["paths"]["panel"])
    logger.info("Flagged outliers: %d (review table in %s)", len(review), interim / "outlier_review.csv")


if __name__ == "__main__":
    main()
