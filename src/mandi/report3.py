"""Phase 3: write docs/model_numbers.md from the files in results/ (no number is typed by hand)."""
from __future__ import annotations

import logging
from typing import Any

import pandas as pd
import yaml

from mandi.config import ROOT, load_config
from mandi.run_phase1 import df_to_md

logger = logging.getLogger(__name__)

PCT_COLS = ["improvement_pct", "test_best_improvement_pct", "log_improvement_pct", "impr_ets_pct", "impr_sarima_pct", "impr_prophet_pct", "impr_lgbm_pct"]


def _fmt(df: pd.DataFrame) -> pd.DataFrame:
    """Round for display: percentages to 1 decimal, rupee/other floats to 2-3 significant decimals."""
    out = df.copy()
    for c in out.columns:
        name = str(c)
        if pd.api.types.is_float_dtype(out[c]):
            if name in PCT_COLS or name.endswith("_pct"):
                out[c] = out[c].round(1)
            elif name in ("DM",):
                out[c] = out[c].round(2)
            elif name in ("p_value", "p_holm"):
                out[c] = out[c].round(4)
            elif name.startswith("MAE_log") or name.startswith("logMAE") or name.startswith("score") or name.startswith("fold_"):
                out[c] = out[c].round(4)
            else:
                out[c] = out[c].round(2)
    return out


def _read(name: str, prefix: str = "") -> pd.DataFrame | None:
    p = ROOT / "results" / f"{prefix}{name}.csv"
    return pd.read_csv(p) if p.exists() else None


def build(cfg: dict[str, Any]) -> str:
    """Assemble the markdown document."""
    sel = yaml.safe_load((ROOT / cfg["forecast"]["selected_models_file"]).read_text(encoding="utf-8"))
    doc = ["# Phase 3 numbers (generated by `python -m mandi.run_phase3 report`)", "",
           "Every number below is read from `results/`. Rupee-scale metrics unless a column says `log`. "
           "Baselines: `base_naive` = last observed quote, `base_mean3` = mean of the last 3 observed quotes, `base_seasonal` = 365-day seasonal-naive. "
           "Improvement = 100 x (strongest baseline MAE - model MAE) / strongest baseline MAE; positive = better than the baseline.", ""]
    doc += ["## Frozen model selection (chosen on the 2017-2019 tuning folds only)", "", f"Tuning run: `{sel['tuning_run']}`.", ""]
    ch = pd.DataFrame([{"h": h, **d} for h, d in sel["chosen"].items()])
    doc += [df_to_md(ch), "Model chosen per market and horizon on the tuning folds (the headline model, fixed before 2020-2024 was run):", "",
            df_to_md(pd.DataFrame(sel["best_model_by_validation"]).pivot(index="market", columns="h", values="model").reset_index()), ""]
    for title, name, prefix in [("Summary: improvement over the strongest baseline per market and horizon", "summary_table", ""),
                                ("Macro average over the five markets (equal weight)", "summary_macro", "")]:
        df = _read(name, prefix)
        if df is not None:
            doc += [f"## {title}", "", df_to_md(_fmt(df)), ""]
    for title, name in [("All metrics per market, horizon and model", "backtest_metrics"),
                        ("Diebold-Mariano test against the strongest baseline (validation-chosen and test-best model)", "dm_tests"),
                        ("Diebold-Mariano test, every model family against the strongest baseline", "dm_all_models"),
                        ("Triples that a model could not forecast", "dropped_triples"), ("Runtime per model", "runtime"),
                        ("Error analysis (log-scale MAE pooled over markets; baseline = strongest baseline per market and horizon, model = validation-chosen)", "error_analysis"),
                        ("Sensitivity (b): with and without is_stale dates", "sensitivity_stale")]:
        df = _read(name)
        if df is not None:
            doc += [f"## {title}", "", df_to_md(_fmt(df)), ""]
    main, err = _read("summary_table"), _read("summary_table", "sens_error_")
    if main is not None and err is not None:
        cmp = main[["market", "h", "n", "strongest_baseline", "validation_chosen_model", "improvement_pct"]].merge(
            err[["market", "h", "n", "strongest_baseline", "validation_chosen_model", "improvement_pct"]], on=["market", "h"], suffixes=("_main", "_error_set_missing"))
        doc += ["## Sensitivity (a): every 'likely error' flagged point set to missing (same frozen models, refit on that panel)", "", df_to_md(_fmt(cmp)), ""]
        em = _read("summary_macro")
        es = _read("summary_macro", "sens_error_")
        if em is not None and es is not None:
            doc += ["Macro average improvement, main vs error-set-missing:", "", df_to_md(_fmt(em[["h", "improvement_pct"]].merge(es[["h", "improvement_pct"]], on="h", suffixes=("_main", "_error_set_missing")))), ""]
    return "\n".join(doc)


def main() -> None:
    """Write docs/model_numbers.md."""
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    cfg = load_config()
    (ROOT / cfg["paths"]["docs"] / "model_numbers.md").write_text(build(cfg), encoding="utf-8")
    logger.info("wrote docs/model_numbers.md")


if __name__ == "__main__":
    main()
